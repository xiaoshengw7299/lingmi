import http from './http';

export const login = (username: string, password: string) => http.post('/admin/auth/login', { username, password });
export const profile = () => http.get('/admin/auth/profile');
export const dashboard = () => http.get('/admin/dashboard/stats');
export const wallets = (params: Record<string, unknown>) => http.get('/admin/wallets', { params });
export const walletDetail = (id: string) => http.get(`/admin/wallets/${id}`);
export const patchWallet = (id: string, data: Record<string, unknown>) => http.patch(`/admin/wallets/${id}`, data);
export const adjustWallet = (id: string, data: Record<string, unknown>) => http.post(`/admin/wallets/${id}/adjust`, data);
export const orders = (params: Record<string, unknown>) => http.get('/admin/orders', { params });
export const syncOrder = (orderNo: string) => http.post(`/admin/orders/${orderNo}/sync`);
export const closeOrder = (orderNo: string) => http.post(`/admin/orders/${orderNo}/close`);
export const refunds = (params: Record<string, unknown>) => http.get('/admin/refunds', { params });
export const createRefund = (data: Record<string, unknown>) => http.post('/admin/refunds', data);
export const syncRefund = (refundNo: string) => http.post(`/admin/refunds/${refundNo}/sync`);
export const transfers = (params: Record<string, unknown>) => http.get('/admin/transfers', { params });
export const createTransfer = (data: Record<string, unknown>) => http.post('/admin/transfers', data);
export const syncTransfer = (transferNo: string) => http.post(`/admin/transfers/${transferNo}/sync`);
export const receivers = () => http.get('/admin/division/receivers');
export const createReceiver = (data: Record<string, unknown>) => http.post('/admin/division/receivers', data);
export const patchReceiver = (id: string, data: Record<string, unknown>) => http.patch(`/admin/division/receivers/${id}`, data);
export const bindReceiver = (id: string) => http.post(`/admin/division/receivers/${id}/bind`);
export const unbindReceiver = (id: string) => http.post(`/admin/division/receivers/${id}/unbind`);
export const divisionRecords = (params: Record<string, unknown>) => http.get('/admin/division/records', { params });
export const execDivision = (orderNo: string) => http.post('/admin/division/exec', { orderNo });
export const queryDivision = (batchNo: string) => http.post('/admin/division/query', { batchNo });
export const getAlipay = () => http.get('/admin/config/alipay');
export const saveAlipay = (data: Record<string, unknown>) => http.patch('/admin/config/alipay', data);
export const pingAlipay = () => http.post('/admin/config/alipay/ping');
export const testAlipayPay = () => http.post('/admin/config/alipay/test-pay');
export const settings = () => http.get('/admin/config/settings');
export const saveSetting = (key: string, value: string) => http.patch('/admin/config/settings', { key, value });
export const iamUsers = () => http.get('/admin/iam/users');
export const createIamUser = (data: Record<string, unknown>) => http.post('/admin/iam/users', data);
export const patchIamUser = (id: string, data: Record<string, unknown>) => http.patch(`/admin/iam/users/${id}`, data);
export const iamRoles = () => http.get('/admin/iam/roles');
export const saveRole = (data: Record<string, unknown>, id?: string) =>
  id ? http.patch(`/admin/iam/roles/${id}`, data) : http.post('/admin/iam/roles', data);
export const iamPerms = () => http.get('/admin/iam/permissions');
export const auditLogs = (params: Record<string, unknown>) => http.get('/admin/audit-logs', { params });
export const reconBatches = (params: Record<string, unknown>) => http.get('/admin/recon/batches', { params });
export const reconItems = (params: Record<string, unknown>) => http.get('/admin/recon/items', { params });
export const reconSummary = (billDate?: string) => http.get('/admin/recon/summary', { params: { billDate } });
export const runRecon = (billDate: string, endDate?: string) => http.post('/admin/recon/run', { billDate, endDate }, { timeout: 600000 });
export const handleRecon = (id: string, action: string, remark?: string) => http.post(`/admin/recon/items/${id}/handle`, { action, remark });
